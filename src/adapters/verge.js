import fs from "node:fs";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { parseYaml, dumpYaml } from "../core/yaml.js";

const exec = promisify(execFile);

export class VergeAdapter {
  constructor(frontend) {
    this.frontend = frontend;
    this.id = "clash-verge-rev";
    this.label = frontend?.label ?? "Clash Verge Rev";
  }

  get targetFile() {
    return this.frontend?.mergeFile ?? null;
  }

  async prepare() {
    if (!this.targetFile) {
      throw new Error(
        "could not locate the active profile's merge enhancement file in profiles.yaml; " +
          "make sure a merge enhancement is configured for the current profile",
      );
    }
    if (!fs.existsSync(this.targetFile)) {
      throw new Error(`merge file not found: ${this.targetFile}`);
    }
    return { file: this.targetFile };
  }

  readCurrentDns() {
    const text = fs.readFileSync(this.targetFile, "utf8");
    const parsed = parseYaml(text);
    return parsed.dns && typeof parsed.dns === "object" ? parsed.dns : {};
  }

  renderDnsBlock(dns) {
    return dumpYaml({ dns }, 0);
  }

  async apply(dnsSection) {
    const text = fs.readFileSync(this.targetFile, "utf8");
    const block = this.renderDnsBlock(dnsSection);
    const header = [
      "# netfix managed block — internal-network DNS routing.",
      "# Regenerated by `netfix fix`; edit the tool, not this file.",
    ].join("\n");

    // Preserve any non-dns content already in the merge file.
    const lines = text.split("\n");
    const dnsStart = lines.findIndex((l) => /^dns:/.test(l));
    let kept = [];
    if (dnsStart !== -1) {
      let end = dnsStart + 1;
      while (end < lines.length) {
        const line = lines[end];
        if (line.trim() && /^\S/.test(line)) break;
        end += 1;
      }
      kept = [...lines.slice(0, dnsStart), ...lines.slice(end)];
    } else {
      kept = lines;
    }

    const body = kept.join("\n").replace(/\s+$/, "");
    const output = body ? `${body}\n\n${header}\n${block}\n` : `${header}\n${block}\n`;
    fs.writeFileSync(this.targetFile, output, "utf8");
    return { file: this.targetFile, needsRestart: true };
  }

  // The running core loads its config from a root-owned runtime directory that
  // the mihomo API refuses to load from external paths (SAFE_PATHS), so the
  // only way to regenerate it is to restart the GUI.
  async reload() {
    await this.restartGui();
  }

  async restartGui() {
    try {
      await exec("osascript", ["-e", 'quit app "Clash Verge"'], { timeout: 10000 });
    } catch {
      // App may not be running under that exact name
    }
    await new Promise((r) => setTimeout(r, 2500));
    try {
      await exec("pkill", ["-f", "Clash Verge.app/Contents/MacOS/clash-verge"], { timeout: 5000 });
    } catch {
      // nothing to kill
    }
    await new Promise((r) => setTimeout(r, 1500));
    await exec("open", ["-a", "Clash Verge"], { timeout: 10000 });
  }
}
